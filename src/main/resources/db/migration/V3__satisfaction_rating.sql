-- V3: 만족도 평가 (기획서 4.6, 공통 기능 P1)
--   S05 사례 생성 평가(프로젝트마다 한 번), S09 방향 제시 평가(공고마다 한 번).
--   회원·대상마다 하나만 두고 다시 평가하면 덮어쓴다(마지막 값만). 평가할 때의 회차를 함께 남겨 피드백 전후 비교에 쓴다.
-- =====================================================================
CREATE TABLE app.satisfaction_rating (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        bigint      NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    target_type      varchar(30) NOT NULL CHECK (target_type IN ('EPISODE_GENERATION', 'GUIDE')),
    target_id        bigint      NOT NULL,                 -- project id 또는 job_posting id (대상이 지워져도 KPI 용으로 남긴다, FK 없음)
    score            integer     NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment          varchar(300),
    split_round      integer,                              -- 사례 생성 평가: 평가할 때의 나누기 회차
    fit_analysis_id  bigint,                               -- 방향 제시 평가: 평가할 때의 분석
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_satisfaction_rating UNIQUE (member_id, target_type, target_id)
);
