-- =====================================================================
-- V1: nerdnam 초기 스키마
--   app 스키마 : 원본 데이터 (회원, 기술 사전, 기술스택, 경력, 프로젝트·사례, 공고, 적합도 분석, 작성 방향)
--   rag 스키마 : 검색용 청크 + 임베딩 벡터 (pgvector)
--
-- 규칙
--   * PK는 bigint identity. 외부에 노출해도 되도록 모든 조회는 member_id 소유 확인을 거친다.
--   * enum 값은 varchar + CHECK 로 저장한다. (Java enum 이름 그대로, @Enumerated(EnumType.STRING))
--   * 시간은 timestamptz(UTC). 월 단위 기간(YYYY-MM)은 date(해당 월 1일)로 저장한다.
--   * 회원 탈퇴 = member 행 삭제. ON DELETE CASCADE 로 원본·벡터가 한 번에 지워진다. (기획서 8장)
--   * 다른 애그리거트를 가리키는 FK(경력·프로젝트 → 기술스택, 프로젝트 → 경력)는 CASCADE / SET NULL 로 둔다.
--     NO ACTION 으로 두면 탈퇴 시 연쇄 삭제 순서 때문에 member 삭제가 실패한다(로컬 검증에서 확인).
--     "쓰이는 기술을 지워도 되나" 같은 정책은 DB가 아니라 애플리케이션 서비스가 삭제 전에 판단한다.
--   * 확장(extension)은 public 스키마에 설치하고 타입·연산자를 public. 으로 명시한다.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS vector  WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS rag;

-- ---------------------------------------------------------------------
-- 1. 회원 (identity 컨텍스트)
-- ---------------------------------------------------------------------
CREATE TABLE app.member (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           varchar(255),
    display_name    varchar(50)  NOT NULL,
    last_login_at   timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_member_email ON app.member (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE app.social_account (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         bigint       NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    provider          varchar(20)  NOT NULL CHECK (provider IN ('GOOGLE', 'KAKAO')),
    provider_user_id  varchar(255) NOT NULL,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_social_account UNIQUE (provider, provider_user_id)
);
CREATE INDEX ix_social_account_member ON app.social_account (member_id);

CREATE TABLE app.member_consent (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     bigint      NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    consent_type  varchar(30) NOT NULL CHECK (consent_type IN ('TERMS_OF_SERVICE', 'PRIVACY_COLLECTION')),
    terms_version varchar(20) NOT NULL,
    agreed_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_member_consent UNIQUE (member_id, consent_type, terms_version)
);

-- ---------------------------------------------------------------------
-- 2. 표준 기술 사전 (skill catalog 컨텍스트) — 전체 사용자 공용
-- ---------------------------------------------------------------------
CREATE TABLE app.skill (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,                 -- 표시용 표준 이름 (예: Spring Boot)
    name_key    varchar(100) NOT NULL,                 -- 정규화 키 (예: springboot)
    category    varchar(20)  NOT NULL CHECK (category IN ('LANGUAGE', 'FRAMEWORK', 'DATABASE', 'INFRA', 'TOOL')),
    status      varchar(20)  NOT NULL DEFAULT 'OFFICIAL' CHECK (status IN ('OFFICIAL', 'USER_ADDED')),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_skill_name_key UNIQUE (name_key)
);
-- 자동완성(부분 일치)용
CREATE INDEX ix_skill_name_key_trgm ON app.skill USING gin (name_key public.gin_trgm_ops);

CREATE TABLE app.skill_alias (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id    bigint       NOT NULL REFERENCES app.skill (id) ON DELETE CASCADE,
    alias       varchar(100) NOT NULL,                 -- 예: react.js, 리액트
    alias_key   varchar(100) NOT NULL,
    CONSTRAINT uk_skill_alias_key UNIQUE (alias_key)
);
CREATE INDEX ix_skill_alias_skill ON app.skill_alias (skill_id);

-- 사전에 없어서 정규화하지 못한 기술명 (사전 보강용 기록)
CREATE TABLE app.unregistered_skill_name (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_name          varchar(100) NOT NULL,
    name_key          varchar(100) NOT NULL,
    source            varchar(20)  NOT NULL CHECK (source IN ('JOB_POSTING', 'PROFILE')),
    occurrence_count  integer      NOT NULL DEFAULT 1,
    first_seen_at     timestamptz  NOT NULL DEFAULT now(),
    last_seen_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_unregistered_skill_name UNIQUE (name_key, source)
);

-- ---------------------------------------------------------------------
-- 3. 기술스택·경력 (profile 컨텍스트)
-- ---------------------------------------------------------------------
CREATE TABLE app.user_skill (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   bigint      NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    skill_id    bigint      NOT NULL REFERENCES app.skill (id),
    level       smallint    NOT NULL CHECK (level BETWEEN 1 AND 4),   -- 1 학습 중, 2 실무 사용, 3 능숙, 4 전문가
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_skill UNIQUE (member_id, skill_id)
);
CREATE INDEX ix_user_skill_skill ON app.user_skill (skill_id);

CREATE TABLE app.career (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        bigint       NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    company_name     varchar(100) NOT NULL,
    team_name        varchar(100) NOT NULL,
    job_title        varchar(100) NOT NULL,
    position_title   varchar(50),                                     -- 직급 (선택)
    employment_type  varchar(20)  NOT NULL CHECK (employment_type IN ('FULL_TIME', 'CONTRACT', 'INTERN', 'FREELANCE')),
    start_month      date         NOT NULL,
    end_month        date,                                            -- null = 재직 중
    version          bigint       NOT NULL DEFAULT 0,                 -- 낙관적 락 (@Version)
    created_at       timestamptz  NOT NULL DEFAULT now(),
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_career_month_first_day CHECK (extract(day FROM start_month) = 1 AND (end_month IS NULL OR extract(day FROM end_month) = 1)),
    CONSTRAINT ck_career_period CHECK (end_month IS NULL OR end_month >= start_month)
);
CREATE INDEX ix_career_member ON app.career (member_id);

-- 주요 업무 (최대 5줄) — @ElementCollection
CREATE TABLE app.career_duty (
    career_id  bigint       NOT NULL REFERENCES app.career (id) ON DELETE CASCADE,
    line_no    smallint     NOT NULL CHECK (line_no BETWEEN 0 AND 4),
    content    varchar(300) NOT NULL,
    PRIMARY KEY (career_id, line_no)
);

-- 경력에 연결한 기술 — @ElementCollection (user_skill id 참조)
CREATE TABLE app.career_skill (
    career_id      bigint NOT NULL REFERENCES app.career (id) ON DELETE CASCADE,
    user_skill_id  bigint NOT NULL REFERENCES app.user_skill (id) ON DELETE CASCADE,
    PRIMARY KEY (career_id, user_skill_id)
);
CREATE INDEX ix_career_skill_user_skill ON app.career_skill (user_skill_id);

-- ---------------------------------------------------------------------
-- 4. 프로젝트·사례(에피소드) (experience 컨텍스트) — 핵심 도메인
-- ---------------------------------------------------------------------
CREATE TABLE app.project (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         bigint       NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    title             varchar(100) NOT NULL,
    period_start      date,
    period_end        date,
    affiliation       varchar(20)  NOT NULL CHECK (affiliation IN ('CAREER', 'PERSONAL', 'TEAM')),
    career_id         bigint       REFERENCES app.career (id) ON DELETE SET NULL,  -- affiliation = CAREER 일 때 (도메인에서 검증)
    raw_text          text         NOT NULL DEFAULT '',                -- 사용자가 쓴 원문 (항상 보관)
    status            varchar(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'REVIEW', 'CONFIRMED')),
    split_round       integer      NOT NULL DEFAULT 0 CHECK (split_round >= 0),        -- 나누기 회차 (첫 나누기 = 1, 다시 나누기마다 +1)
    generation_count  integer      NOT NULL DEFAULT 0 CHECK (generation_count >= 0),   -- AI 생성 누적 횟수. 상한 없음, KPI·비용 측정용 (ADR-0002)
    needs_resplit     boolean      NOT NULL DEFAULT false,                             -- 나눈 뒤 원문을 고침 → 다시 나누기 전에는 확정 불가
    last_confirmed_at timestamptz,                                                     -- 마지막 확정 시각. 재등록 중(DRAFT/REVIEW)에도 남아 "확정본 있음"을 뜻한다
    version           bigint       NOT NULL DEFAULT 0,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_project_period CHECK (period_end IS NULL OR period_start IS NULL OR period_end >= period_start)
);
CREATE INDEX ix_project_member ON app.project (member_id);
CREATE INDEX ix_project_career ON app.project (career_id);

CREATE TABLE app.project_skill (
    project_id     bigint NOT NULL REFERENCES app.project (id) ON DELETE CASCADE,
    user_skill_id  bigint NOT NULL REFERENCES app.user_skill (id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, user_skill_id)
);
CREATE INDEX ix_project_skill_user_skill ON app.project_skill (user_skill_id);

CREATE TABLE app.project_link (
    project_id  bigint        NOT NULL REFERENCES app.project (id) ON DELETE CASCADE,
    line_no     smallint      NOT NULL,
    url         varchar(1000) NOT NULL,
    PRIMARY KEY (project_id, line_no)
);

-- 확인 질문에 대한 답 (원문 뒤에 순서대로 덧붙여 AI 입력 원문을 만든다)
CREATE TABLE app.project_supplement (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  bigint      NOT NULL REFERENCES app.project (id) ON DELETE CASCADE,
    episode_id  bigint,                                                -- 어떤 사례의 질문이었는지 (사례가 대체돼도 기록은 남김)
    question    text        NOT NULL,
    answer      text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_project_supplement_project ON app.project_supplement (project_id, id);

CREATE TABLE app.episode (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id       bigint      NOT NULL REFERENCES app.project (id) ON DELETE CASCADE,
    split_round      integer     NOT NULL,                                               -- 몇 번째 나누기에서 만들어졌는지 (직접 추가는 그때의 회차)
    display_order    smallint    NOT NULL,
    origin           varchar(20) NOT NULL CHECK (origin IN ('AI', 'USER')),            -- AI가 나눔 / 사용자가 직접 추가
    status           varchar(20) NOT NULL DEFAULT 'REVIEW'
                         CHECK (status IN ('REVIEW', 'CONFIRMED', 'EXCLUDED', 'SUPERSEDED')), -- SUPERSEDED = 다시 나누기로 대체됨
    current_version  integer     NOT NULL DEFAULT 1,
    decided_at       timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_episode_project ON app.episode (project_id, status);

-- 사례 버전 이력 — 한 번 만든 버전은 바꾸지 않는다 (append-only)
CREATE TABLE app.episode_version (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    episode_id      bigint       NOT NULL REFERENCES app.episode (id) ON DELETE CASCADE,
    version_no      integer      NOT NULL CHECK (version_no >= 1),
    title           varchar(100) NOT NULL,
    role            varchar(200),
    problem         text         NOT NULL DEFAULT '',
    solution        text         NOT NULL DEFAULT '',
    result          text         NOT NULL DEFAULT '',
    skills          jsonb        NOT NULL DEFAULT '[]',   -- ["Spring Boot", "Redis"]
    metrics         jsonb        NOT NULL DEFAULT '[]',   -- [{"name","before","after","source"}]
    source_spans    jsonb        NOT NULL DEFAULT '[]',   -- [[0,182]]
    clarifications  jsonb        NOT NULL DEFAULT '[]',   -- 확인 필요 질문 [{"key","field","question"}] (비어야 확정 가능)
    change_type     varchar(20)  NOT NULL CHECK (change_type IN ('AI_SPLIT', 'AI_REVISION', 'USER_EDIT', 'USER_CREATED')),
    feedback        text,                                 -- 수정 요청 문장
    ai_model        varchar(100),
    prompt_version  varchar(50),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_episode_version UNIQUE (episode_id, version_no)
);

-- ---------------------------------------------------------------------
-- 5. 채용공고 (job posting 컨텍스트)
--   임시 저장을 허용하므로 필수 항목·150자 검증은 DB가 아니라 "분석 시작" 시점에 도메인이 한다.
-- ---------------------------------------------------------------------
CREATE TABLE app.job_posting (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      bigint        NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    company_name   varchar(200)  NOT NULL DEFAULT '',
    position_name  varchar(200)  NOT NULL DEFAULT '',
    posting_url    varchar(1000),
    company_intro  text          NOT NULL DEFAULT '',
    version        bigint        NOT NULL DEFAULT 0,
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_job_posting_member ON app.job_posting (member_id, created_at DESC);

CREATE TABLE app.job_requirement (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id  bigint        NOT NULL REFERENCES app.job_posting (id) ON DELETE CASCADE,
    type            varchar(20)   NOT NULL CHECK (type IN ('REQUIRED', 'PREFERRED')),
    line_no         smallint      NOT NULL,
    text            varchar(1000) NOT NULL,                -- 150자 제한은 분석 시작 시 검증
    skills_raw      jsonb,                                 -- AI 추출 원문 기술명
    skills          jsonb,                                 -- API가 정규화한 기술명
    min_years       smallint CHECK (min_years IS NULL OR min_years >= 0),
    extracted_at    timestamptz
);
CREATE INDEX ix_job_requirement_posting ON app.job_requirement (job_posting_id, type, line_no);

-- 주요 업무 (지원동기용, 판정·임베딩에 쓰지 않음) — @ElementCollection
CREATE TABLE app.job_posting_task (
    job_posting_id  bigint        NOT NULL REFERENCES app.job_posting (id) ON DELETE CASCADE,
    line_no         smallint      NOT NULL,
    content         varchar(1000) NOT NULL,
    PRIMARY KEY (job_posting_id, line_no)
);

-- ---------------------------------------------------------------------
-- 6. 적합도 분석 (matching 컨텍스트)
--   분석 시점의 요건 문구를 복사해 둔다. 공고를 고친 뒤 다시 분석해도 이전 결과가 깨지지 않게.
-- ---------------------------------------------------------------------
CREATE TABLE app.fit_analysis (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       bigint       NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    job_posting_id  bigint       NOT NULL REFERENCES app.job_posting (id) ON DELETE CASCADE,
    status          varchar(20)  NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'FAILED')),
    failure_code    varchar(50),
    ai_model        varchar(100),
    prompt_version  varchar(50),
    requested_at    timestamptz  NOT NULL DEFAULT now(),
    completed_at    timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_fit_analysis_posting ON app.fit_analysis (job_posting_id, requested_at DESC);
CREATE INDEX ix_fit_analysis_member ON app.fit_analysis (member_id);

CREATE TABLE app.requirement_match (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fit_analysis_id   bigint        NOT NULL REFERENCES app.fit_analysis (id) ON DELETE CASCADE,
    requirement_id    bigint,                               -- FK 없음: 요건이 수정·삭제돼도 결과는 남긴다
    requirement_type  varchar(20)   NOT NULL CHECK (requirement_type IN ('REQUIRED', 'PREFERRED')),
    requirement_text  varchar(1000) NOT NULL,               -- 분석 시점 스냅샷
    display_order     smallint      NOT NULL,
    skills            jsonb         NOT NULL DEFAULT '[]',
    min_years         smallint,
    rule_verdict      varchar(20) CHECK (rule_verdict IN ('MET', 'PARTIAL', 'UNMET')),   -- 연차 규칙 판정 (해당 없으면 null)
    llm_verdict       varchar(20) CHECK (llm_verdict  IN ('MET', 'PARTIAL', 'UNMET')),
    final_verdict     varchar(20)   NOT NULL CHECK (final_verdict IN ('MET', 'PARTIAL', 'UNMET')),
    reason            text
);
CREATE INDEX ix_requirement_match_analysis ON app.requirement_match (fit_analysis_id, display_order);

-- 판정 근거. 청크는 재등록 때 지워질 수 있으므로 chunk_id 에 FK를 걸지 않고 원본 출처(source)를 함께 저장한다.
CREATE TABLE app.match_evidence (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_match_id  bigint      NOT NULL REFERENCES app.requirement_match (id) ON DELETE CASCADE,
    rank_no               smallint    NOT NULL,
    chunk_id              bigint      NOT NULL,
    source_type           varchar(20) NOT NULL CHECK (source_type IN ('SKILL', 'CAREER', 'PROJECT_SUMMARY', 'EPISODE')),
    source_id             bigint      NOT NULL,
    source_version        integer     NOT NULL,
    snippet               text        NOT NULL
);
CREATE INDEX ix_match_evidence_match ON app.match_evidence (requirement_match_id, rank_no);

-- ---------------------------------------------------------------------
-- 7. 작성 방향 (guide 컨텍스트) — AI가 만든 JSON을 그대로 보관, 탭별로 다시 만들기 이력 유지
-- ---------------------------------------------------------------------
CREATE TABLE app.writing_guide (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fit_analysis_id  bigint      NOT NULL REFERENCES app.fit_analysis (id) ON DELETE CASCADE,
    tab              varchar(30) NOT NULL CHECK (tab IN ('MOTIVATION', 'SELF_INTRODUCTION', 'PORTFOLIO', 'CAREER_DESCRIPTION', 'IMAGE_PROMPT')),
    generation_no    integer     NOT NULL CHECK (generation_no >= 1),
    status           varchar(20) NOT NULL DEFAULT 'GENERATING' CHECK (status IN ('GENERATING', 'COMPLETED', 'FAILED')),
    content          jsonb,
    feedback         text,
    ai_model         varchar(100),
    prompt_version   varchar(50),
    created_at       timestamptz NOT NULL DEFAULT now(),
    completed_at     timestamptz,
    CONSTRAINT uk_writing_guide UNIQUE (fit_analysis_id, tab, generation_no)
);

-- ---------------------------------------------------------------------
-- 8. AI 호출 기록 — 비용·지연·KPI(재구성 횟수 등) 측정용
-- ---------------------------------------------------------------------
CREATE TABLE app.ai_call_log (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       bigint      REFERENCES app.member (id) ON DELETE CASCADE,
    operation       varchar(30) NOT NULL CHECK (operation IN ('RESTRUCTURE', 'EXTRACT_REQUIREMENTS', 'EMBED', 'MATCH', 'GUIDE')),
    target_type     varchar(30),
    target_id       bigint,
    ai_model        varchar(100),
    prompt_version  varchar(50),
    success         boolean     NOT NULL,
    error_code      varchar(50),
    latency_ms      integer,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_ai_call_log_created ON app.ai_call_log (created_at);

-- =====================================================================
-- rag 스키마
-- =====================================================================
CREATE TABLE rag.chunk (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        bigint       NOT NULL REFERENCES app.member (id) ON DELETE CASCADE,
    chunk_type       varchar(20)  NOT NULL CHECK (chunk_type IN ('SKILL', 'CAREER', 'PROJECT_SUMMARY', 'EPISODE')),
    source_id        bigint       NOT NULL,          -- user_skill / career / project / episode 의 id
    source_version   integer      NOT NULL,          -- episode 는 version_no, 나머지는 엔티티 version
    project_id       bigint,                         -- EPISODE / PROJECT_SUMMARY 청크의 프로젝트. 재확정 때 프로젝트 청크를 통째로 교체하는 데 쓴다
    content         text         NOT NULL,          -- 임베딩한 텍스트 (판정·인용 원문)
    skills           text[]       NOT NULL DEFAULT '{}',   -- 정규화된 기술명 (키워드 검색 &&)
    period_start     date,
    period_end       date,
    months           integer,
    has_metric       boolean      NOT NULL DEFAULT false,
    embedding_status varchar(20)  NOT NULL DEFAULT 'PENDING' CHECK (embedding_status IN ('PENDING', 'READY')),  -- GPU 서버가 꺼져 있으면 PENDING 으로 저장 후 재처리 (기획서 8장)
    embedding        public.vector(768),             -- embeddinggemma-2 = 768차원 (ADR-0001). 모델 교체 시 마이그레이션 + 전체 재임베딩
    embedding_model  varchar(200),                   -- 예: google/embeddinggemma-2@<rev>:768
    created_at       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_chunk_source UNIQUE (member_id, chunk_type, source_id, source_version),
    CONSTRAINT ck_chunk_embedding_ready CHECK (
        (embedding_status = 'READY'   AND embedding IS NOT NULL AND embedding_model IS NOT NULL) OR
        (embedding_status = 'PENDING' AND embedding IS NULL))
);
